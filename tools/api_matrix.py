#!/usr/bin/env python3
"""Generate docs/api-coverage.md, the Trakt API coverage matrix, from the published OpenAPI document.

The matrix lists every operation of the Trakt API with its section, the access markers the Trakt documentation sets
(OAuth, VIP, pagination, extended info, filters) and this plugin's implementation status. Statuses live in
docs/api/coverage-status.json; an operation it does not name is "planned".

    python3 tools/api_matrix.py            # fetch, verify the pinned digest, write the matrix
    python3 tools/api_matrix.py --check    # fail when the committed matrix differs from a fresh render
    python3 tools/api_matrix.py --spec F   # render from a local copy of the document instead of fetching

The document is not committed (it is Trakt's); docs/api/source.json pins its address and SHA-256. A fetched document
whose digest differs fails with both digests, so an API change is a reviewed update of source.json, never a silent one.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "docs" / "api" / "source.json"
STATUS = ROOT / "docs" / "api" / "coverage-status.json"
MATRIX = ROOT / "docs" / "api-coverage.md"
METHODS = ("get", "post", "put", "patch", "delete")
STATUSES = ("planned", "implemented", "out-of-scope")
FETCH_TIMEOUT_SECONDS = 60
MAX_SPEC_BYTES = 32 * 1024 * 1024

# Marker text in the first "####" heading of an operation description -> matrix column value. Allow-list: a heading
# word not listed here is reported, never guessed.
MARKERS = {
    "OAuth Required": ("auth", "required"),
    "OAuth Optional": ("auth", "optional"),
    "VIP Only": ("vip", "only"),
    "VIP Enhanced": ("vip", "enhanced"),
    "Pagination Optional": ("pagination", "optional"),
    "Pagination": ("pagination", "yes"),
    "Extended Info": ("extended", "yes"),
    "Filters": ("filters", "yes"),
    "Emojis": ("emojis", "yes"),
    "Limited Access": ("limited", "yes"),
}
MARKER_HEADING = re.compile(r"^####\s+(.*)$", re.M)


def markers(description: str) -> dict[str, str]:
    """Access markers of one operation, from the first marker heading of its description."""
    found = {"auth": "none", "vip": "no", "pagination": "no", "extended": "no", "filters": "no", "limited": "no"}
    for heading in MARKER_HEADING.findall(description or ""):
        text = heading
        hits = 0
        for name in sorted(MARKERS, key=len, reverse=True):
            if name in text:
                column, value = MARKERS[name]
                found[column] = value
                text = text.replace(name, "")
                hits += 1
        if hits:
            return found
    return found


def operations(spec: dict) -> list[dict]:
    """One row per operation, sorted by section, path and method."""
    rows = []
    for path, item in spec.get("paths", {}).items():
        for method in METHODS:
            op = item.get(method)
            if not isinstance(op, dict):
                continue
            tags = op.get("tags") or ["untagged"]
            rows.append({
                "key": f"{method.upper()} {path}",
                "section": tags[0],
                "method": method.upper(),
                "path": path,
                "summary": " ".join((op.get("summary") or "").split()),
                **markers(op.get("description", "")),
            })
    return sorted(rows, key=lambda row: (row["section"], row["path"], METHODS.index(row["method"].lower())))


def load_status(rows: list[dict], status: dict) -> dict[str, str]:
    """Status per operation key; refuses unknown keys and unknown values so a renamed endpoint cannot hide."""
    keys = {row["key"] for row in rows}
    errors = [f"{key}: not an operation of the pinned document" for key in status if key not in keys]
    errors += [f"{key}: status {value!r} not in {STATUSES}" for key, value in status.items() if value not in STATUSES]
    if errors:
        raise ValueError("docs/api/coverage-status.json:\n  " + "\n  ".join(sorted(errors)))
    return {row["key"]: status.get(row["key"], "planned") for row in rows}


def cell(text: str) -> str:
    return text.replace("|", "\\|")


def render(spec: dict, source: dict, status: dict) -> str:
    rows = operations(spec)
    states = load_status(rows, status)
    sections: dict[str, list[dict]] = {}
    for row in rows:
        sections.setdefault(row["section"], []).append(row)
    done = sum(1 for value in states.values() if value == "implemented")
    lines = [
        "<!-- Generated by tools/api_matrix.py from the document pinned in docs/api/source.json. Do not edit; edit",
        "     docs/api/coverage-status.json and rerun the tool. -->",
        "",
        "# Trakt API coverage",
        "",
        f"Every operation of the Trakt API {spec.get('info', {}).get('version', '?')} as published at "
        f"<{source['url']}> (SHA-256 `{source['sha256'][:16]}`, checked {source['checked']}).",
        "",
        f"{len(rows)} operations in {len(sections)} sections; {done} implemented.",
        "",
        "Columns: *auth* is the OAuth requirement, *vip* marks VIP-only operations (HTTP 426 for other accounts) and",
        "VIP-enhanced ones (HTTP 420 when a free account's limit is reached). The plugin reads VIP status from",
        "`GET /users/settings` (`user.vip`).",
        "",
        "## Sections",
        "",
        "| Section | Operations | Implemented |",
        "|---|---|---|",
    ]
    for name, items in sections.items():
        implemented = sum(1 for row in items if states[row["key"]] == "implemented")
        lines.append(f"| [{name}](#{name.lower()}) | {len(items)} | {implemented} |")
    for name, items in sections.items():
        lines += ["", f"## {name}", "", "| Method | Path | Summary | Auth | VIP | Pagination | Extended | Status |",
                  "|---|---|---|---|---|---|---|---|"]
        for row in items:
            lines.append(
                f"| {row['method']} | `{cell(row['path'])}` | {cell(row['summary'])} | {row['auth']} | {row['vip']} | "
                f"{row['pagination']} | {row['extended']} | {states[row['key']]} |")
    return "\n".join(lines) + "\n"


def fetch(source: dict) -> bytes:
    request = urllib.request.Request(source["url"], headers={"User-Agent": "jellysin-plugin-trakt api_matrix"})
    with urllib.request.urlopen(request, timeout=FETCH_TIMEOUT_SECONDS) as response:  # noqa: S310 (pinned https URL)
        body = response.read(MAX_SPEC_BYTES + 1)
    if len(body) > MAX_SPEC_BYTES:
        raise ValueError(f"{source['url']}: document larger than {MAX_SPEC_BYTES} bytes")
    return body


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description="Generate the Trakt API coverage matrix.")
    parser.add_argument("--check", action="store_true", help="fail when the committed matrix is stale")
    parser.add_argument("--spec", type=Path, help="local copy of the OpenAPI document")
    args = parser.parse_args(argv)
    source = json.loads(SOURCE.read_text(encoding="utf-8"))
    if not source["url"].startswith("https://"):
        print(f"docs/api/source.json: url must be https: {source['url']}", file=sys.stderr)
        return 2
    body = args.spec.read_bytes() if args.spec else fetch(source)
    digest = hashlib.sha256(body).hexdigest()
    if digest != source["sha256"]:
        print(f"OpenAPI document changed: pinned {source['sha256']}, got {digest}. Review the API change, then update "
              "docs/api/source.json (sha256, checked).", file=sys.stderr)
        return 1
    status = json.loads(STATUS.read_text(encoding="utf-8")) if STATUS.exists() else {}
    try:
        text = render(json.loads(body), source, status)
    except ValueError as error:
        print(error, file=sys.stderr)
        return 1
    if args.check:
        current = MATRIX.read_text(encoding="utf-8") if MATRIX.exists() else ""
        if current != text:
            print("docs/api-coverage.md is stale: run python3 tools/api_matrix.py", file=sys.stderr)
            return 1
        return 0
    MATRIX.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
